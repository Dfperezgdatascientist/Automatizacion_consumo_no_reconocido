-- ============================================================
UPDATE A
FROM DWH_DINERS.BASE_CONSUMOS_NO_RECONOCIDOS_FINAL A,
     (SELECT IDREGISTRO, NUMERO_AUTORIZACION,
             NUMERO_OPERACION, NUMERO_CASO, CREACIONREGISTRO, DECISIONFINAL
      FROM DWH_VIEW.V_AUTOSERVICIO_CONSUMOS_NO_RECONOCIDOS_AUT
      WHERE DECISIONFINAL IS NOT NULL
        AND DECISIONFINAL <> ''
      -- Deduplicar por IDREGISTRO: nos quedamos con el registro más reciente
      QUALIFY ROW_NUMBER() OVER (PARTITION BY IDREGISTRO ORDER BY CREACIONREGISTRO DESC) = 1
     ) B
SET DECISIONFINAL = B.DECISIONFINAL
WHERE (A.DECISIONFINAL IS NULL OR A.DECISIONFINAL = '')
  AND A.IDREGISTRO = B.IDREGISTRO;


