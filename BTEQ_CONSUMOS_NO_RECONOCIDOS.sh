CREATE VOLATILE TABLE VT_XF AS (
    SELECT B.IDREGISTRO, XF.Num_Boleta, XF.Num_Recap, XF.Valor_Movimiento, XF.Valor_IVA,
           XF.FECHA_CORTE, XF.Id_Persona_Cuenta, XF.ID_CUENTA AS XF_ID_CUENTA,
           XF.Fecha_Movimiento AS XF_Fecha_Movimiento, XF.NUM_MOVIMIENTO AS XF_NUM_MOVIMIENTO
    FROM VT_AUT_BASE B
    INNER JOIN DWH_DINERS.MOVIMIENTOS_X_FACTURAR XF
        ON XF.Id_Persona_Cuenta = B.ID_PERSONA
        AND XF.ID_CUENTA = B.ID_CUENTA
        AND XF.Valor_Movimiento = B.Monto_Moneda_Local
        AND B.Fecha_Autorizacion BETWEEN XF.Fecha_Movimiento - 2 AND XF.Fecha_Movimiento + 2
    QUALIFY ROW_NUMBER() OVER (PARTITION BY B.IDREGISTRO
        ORDER BY ABS(B.Fecha_Autorizacion - XF.Fecha_Movimiento) ASC) = 1
) WITH DATA ON COMMIT PRESERVE ROWS;

CREATE VOLATILE TABLE VT_XF2 AS (
    SELECT B.IDREGISTRO, XF2.Num_Boleta, XF2.Num_Recap, XF2.Valor_Movimiento, XF2.Valor_IVA,
           XF2.FECHA_CORTE, XF2.Id_Persona_Cuenta
    FROM VT_AUT_BASE B
    LEFT JOIN VT_XF ON VT_XF.IDREGISTRO = B.IDREGISTRO
    INNER JOIN DWH_DINERS.MOVIMIENTOS_X_FACTURAR XF2
        ON XF2.Id_Persona_Cuenta = B.ID_PERSONA
        AND XF2.ID_CUENTA = B.ID_CUENTA
        AND XF2.ID_TPO_MOVIMIENTO = 1
        AND (ABS(B.Monto_Moneda_Local - XF2.Valor_Movimiento)
             / ((B.Monto_Moneda_Local + XF2.Valor_Movimiento) / 2)) * 100 <= 5.00
        AND B.Fecha_Autorizacion BETWEEN XF2.Fecha_Movimiento - 2 AND XF2.Fecha_Movimiento + 2
    WHERE VT_XF.IDREGISTRO IS NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY B.IDREGISTRO
        ORDER BY ABS(B.Monto_Moneda_Local - XF2.Valor_Movimiento) ASC,
                 ABS(B.Fecha_Autorizacion - XF2.Fecha_Movimiento) ASC) = 1
) WITH DATA ON COMMIT PRESERVE ROWS;

CREATE VOLATILE TABLE VT_EC1 AS (
    SELECT B.IDREGISTRO, EC1.Num_Boleta, EC1.Num_Recap, EC1.Monto_Movimiento, EC1.Monto_IVA,
           EC1.FECHA_CORTE, EC1.Id_Persona, EC1.Id_Doc_Estado_Cuenta,
           EC1.ID_CUENTA AS EC1_ID_CUENTA, EC1.Fecha_Movimiento AS EC1_Fecha_Movimiento
    FROM VT_AUT_BASE B
    LEFT JOIN VT_XF ON VT_XF.IDREGISTRO = B.IDREGISTRO
    LEFT JOIN VT_XF2 ON VT_XF2.IDREGISTRO = B.IDREGISTRO
    INNER JOIN DWH_DINERS.ESTADO_CUENTA_DETALLE EC1
        ON EC1.Id_Persona = B.ID_PERSONA
        AND EC1.ID_CUENTA = B.ID_CUENTA
        AND EC1.Monto_Movimiento = B.Monto_Moneda_Local
        AND B.Fecha_Autorizacion BETWEEN EC1.Fecha_Movimiento - 2 AND EC1.Fecha_Movimiento + 2
    WHERE VT_XF.IDREGISTRO IS NULL AND VT_XF2.IDREGISTRO IS NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY B.IDREGISTRO
        ORDER BY ABS(B.Fecha_Autorizacion - EC1.Fecha_Movimiento) ASC) = 1
) WITH DATA ON COMMIT PRESERVE ROWS;

CREATE VOLATILE TABLE VT_EC2 AS (
    SELECT B.IDREGISTRO, EC2.Num_Boleta, EC2.Num_Recap, EC2.Monto_Movimiento, EC2.Monto_IVA,
           EC2.FECHA_CORTE, EC2.Id_Persona, EC2.Id_Doc_Estado_Cuenta,
           EC2.ID_CUENTA AS EC2_ID_CUENTA, EC2.Fecha_Movimiento AS EC2_Fecha_Movimiento
    FROM VT_AUT_BASE B
    LEFT JOIN VT_XF ON VT_XF.IDREGISTRO = B.IDREGISTRO
    LEFT JOIN VT_XF2 ON VT_XF2.IDREGISTRO = B.IDREGISTRO
    LEFT JOIN VT_EC1 ON VT_EC1.IDREGISTRO = B.IDREGISTRO
    INNER JOIN DWH_DINERS.ESTADO_CUENTA_DETALLE EC2
        ON EC2.Id_Persona = B.ID_PERSONA
        AND EC2.ID_CUENTA = B.ID_CUENTA
        AND EC2.Cod_Tipo_Movimiento_Cuenta_Factura = 1
        AND (ABS(B.Monto_Moneda_Local - EC2.MONTO_MOVIMIENTO)
             / ((B.Monto_Moneda_Local + EC2.MONTO_MOVIMIENTO) / 2)) * 100 <= 5.00
        AND B.Fecha_Autorizacion BETWEEN EC2.Fecha_Movimiento - 2 AND EC2.Fecha_Movimiento + 2
    WHERE VT_XF.IDREGISTRO IS NULL AND VT_XF2.IDREGISTRO IS NULL AND VT_EC1.IDREGISTRO IS NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY B.IDREGISTRO
        ORDER BY ABS(B.Monto_Moneda_Local - EC2.MONTO_MOVIMIENTO) ASC,
                 ABS(B.Fecha_Autorizacion - EC2.Fecha_Movimiento) ASC) = 1
) WITH DATA ON COMMIT PRESERVE ROWS;

